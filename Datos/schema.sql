CREATE TABLE IF NOT EXISTS Producto(
  Id INTEGER PRIMARY KEY AUTOINCREMENT,
  Nombre TEXT NOT NULL,
  Precio REAL NOT NULL CHECK(Precio > 0),
  Stock INTEGER NOT NULL CHECK(Stock >= 0),
  Activo INTEGER NOT NULL DEFAULT 1);
CREATE TABLE IF NOT EXISTS Cliente(
  Id INTEGER PRIMARY KEY AUTOINCREMENT,
  Nombre TEXT NOT NULL,
  Telefono TEXT,
  LimiteCredito REAL NOT NULL CHECK(LimiteCredito >= 0),
  Activo INTEGER NOT NULL DEFAULT 1);
CREATE TABLE IF NOT EXISTS Venta(
  Id INTEGER PRIMARY KEY AUTOINCREMENT,
  Fecha TEXT NOT NULL,
  ClienteId INTEGER NULL REFERENCES Cliente(Id),
  MetodoPago TEXT NOT NULL,
  Total REAL NOT NULL);
CREATE TABLE IF NOT EXISTS DetalleVenta(
  Id INTEGER PRIMARY KEY AUTOINCREMENT,
  VentaId INTEGER NOT NULL REFERENCES Venta(Id),
  ProductoId INTEGER NOT NULL REFERENCES Producto(Id),
  Cantidad INTEGER NOT NULL CHECK(Cantidad > 0),
  PrecioUnitario REAL NOT NULL);
CREATE TABLE IF NOT EXISTS Credito(
  Id INTEGER PRIMARY KEY AUTOINCREMENT,
  ClienteId INTEGER NOT NULL REFERENCES Cliente(Id),
  VentaId INTEGER NOT NULL REFERENCES Venta(Id),
  Monto REAL NOT NULL,
  Saldo REAL NOT NULL CHECK(Saldo >= 0),
  FechaVencimiento TEXT NOT NULL,
  Estado TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS Abono(
  Id INTEGER PRIMARY KEY AUTOINCREMENT,
  CreditoId INTEGER NOT NULL REFERENCES Credito(Id),
  Monto REAL NOT NULL CHECK(Monto > 0),
  Fecha TEXT NOT NULL);
